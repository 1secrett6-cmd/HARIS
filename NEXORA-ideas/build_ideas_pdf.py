def ranking_table():
    allideas = sorted(GOLDEN + ROUND2 + ROUND1, key=lambda d: (-sum(d["s"]), d["n"]))
    rows = []
    for rank, d in enumerate(allideas, 1):
        cls = ' class="top"' if rank <= 5 else ""
        star = " ⭐" if d in GOLDEN else ""
        rows.append(
            f"<tr{cls}><td>{rank}</td><td>{d['emoji']} <b>{e(d['ar'])}</b> <span class='en'>{e(d['en'])}</span>{star}</td>"
            + "".join(f"<td>{v}</td>" for v in d["s"])
            + f"<td class='tot'>{sum(d['s'])}</td></tr>"
        )
    head = "".join(f"<th>{x}</th>" for x in ("#", "الفكرة", *SCORE_LABELS, "المجموع"))
    return f'<table class="rank"><thead><tr>{head}</tr></thead><tbody>{"".join(rows)}</tbody></table>'


